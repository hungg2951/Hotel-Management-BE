-- 1. Bảng CANCELLATION_POLICY: Chính sách hủy đặt phòng
CREATE TABLE cancellation_policy (
    policy_id               NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    policy_code             VARCHAR2(30) NOT NULL,
    name                    VARCHAR2(150) NOT NULL,
    description             VARCHAR2(500),
    free_cancel_hours       NUMBER(5) DEFAULT 72 NOT NULL,
    penalty_type            VARCHAR2(30) DEFAULT 'ONE_NIGHT' NOT NULL,
    penalty_value           NUMBER(15,2) DEFAULT 0 NOT NULL,
    is_default              BOOLEAN DEFAULT FALSE NOT NULL,
    is_active               BOOLEAN DEFAULT TRUE NOT NULL,
    created_at              TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_cancellation_policy PRIMARY KEY (policy_id),
    CONSTRAINT uq_cancellation_policy_code UNIQUE (policy_code),
    CONSTRAINT ck_cancel_penalty_type CHECK (penalty_type IN ('NONE', 'ONE_NIGHT', 'PERCENT_TOTAL', 'PERCENT_DEPOSIT', 'FIXED_AMOUNT', 'FULL_DEPOSIT'))
);

-- 2. Bảng EARLY_CHECKOUT_POLICY: Chính sách trả phòng sớm
CREATE TABLE early_checkout_policy (
    policy_id               NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    policy_code             VARCHAR2(30) NOT NULL,
    name                    VARCHAR2(150) NOT NULL,
    description             VARCHAR2(500),
    penalty_type            VARCHAR2(30) DEFAULT 'NONE' NOT NULL,
    penalty_value           NUMBER(15,2) DEFAULT 0 NOT NULL,
    is_default              BOOLEAN DEFAULT FALSE NOT NULL,
    is_active               BOOLEAN DEFAULT TRUE NOT NULL,
    created_at              TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_early_checkout_policy PRIMARY KEY (policy_id),
    CONSTRAINT uq_early_checkout_policy_code UNIQUE (policy_code),
    CONSTRAINT ck_early_checkout_penalty CHECK (penalty_type IN ('NONE', 'ONE_NIGHT', 'PERCENT_REMAINING', 'FULL_REMAINING'))
);

