-- Quy uoc: khoa chinh NUMBER IDENTITY (du lieu mau dung id 1..99, id do ung dung sinh bat dau tu 100);
--          tien VND dung NUMBER(15,0); cot logic dung BOOLEAN (Oracle 23ai/26ai).
-- Ten rang buoc: pk_ / fk_ / uq_ / ck_ ; index: ix_

-- 1. APP_ROLE: Vai tro phan quyen cua ung dung (ADMIN, MANAGER, ...)
CREATE TABLE app_role (
    role_id               NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    role_code             VARCHAR2(30) NOT NULL,
    role_name             VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_app_role PRIMARY KEY (role_id),
    CONSTRAINT uq_app_role_role_code UNIQUE (role_code)
);

-- 2. EMPLOYEE: Nhan vien khach san
CREATE TABLE employee (
    employee_id           NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    full_name             VARCHAR2(150) NOT NULL,
    phone                 VARCHAR2(20),
    email                 VARCHAR2(150),
    position              VARCHAR2(100),
    hire_date             DATE,
    salary                NUMBER(12,0),
    is_active             BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT pk_employee PRIMARY KEY (employee_id),
    CONSTRAINT uq_employee_email UNIQUE (email),
    CONSTRAINT ck_employee_salary CHECK (salary >= 0)
);

-- 3. USERS: Tai khoan dang nhap ung dung (mat khau BCrypt)
CREATE TABLE users (
    user_id               NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    employee_id           NUMBER,
    role_id               NUMBER NOT NULL,
    username              VARCHAR2(50) NOT NULL,
    password_hash         VARCHAR2(255) NOT NULL,
    is_active             BOOLEAN DEFAULT TRUE NOT NULL,
    last_login_at         TIMESTAMP,
    created_at            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT uq_users_employee_id UNIQUE (employee_id),
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT fk_users_employee_id FOREIGN KEY (employee_id) REFERENCES employee (employee_id),
    CONSTRAINT fk_users_role_id FOREIGN KEY (role_id) REFERENCES app_role (role_id)
);

-- 4. ROOM_TYPE: Hang phong va gia goc
CREATE TABLE room_type (
    room_type_id          NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    name                  VARCHAR2(100) NOT NULL,
    description           VARCHAR2(500),
    max_adults            NUMBER(2) DEFAULT 2 NOT NULL,
    max_children          NUMBER(2) DEFAULT 0 NOT NULL,
    bed_type              VARCHAR2(50),
    area_sqm              NUMBER(6,1),
    base_price            NUMBER(15,0) NOT NULL,
    is_active             BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT pk_room_type PRIMARY KEY (room_type_id),
    CONSTRAINT uq_room_type_name UNIQUE (name),
    CONSTRAINT ck_room_type_max_adults CHECK (max_adults >= 1),
    CONSTRAINT ck_room_type_base_price CHECK (base_price >= 0)
);

-- 5. ROOM: Phong cu the (so phong, trang thai, trang thai don phong)
CREATE TABLE room (
    room_id               NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    room_type_id          NUMBER NOT NULL,
    room_number           VARCHAR2(10) NOT NULL,
    floor_no              NUMBER(3),
    status                VARCHAR2(20) DEFAULT 'AVAILABLE' NOT NULL,
    housekeeping_status   VARCHAR2(20) DEFAULT 'CLEAN' NOT NULL,
    is_active             BOOLEAN DEFAULT TRUE NOT NULL,
    note                  VARCHAR2(500),
    CONSTRAINT pk_room PRIMARY KEY (room_id),
    CONSTRAINT uq_room_room_number UNIQUE (room_number),
    CONSTRAINT fk_room_room_type_id FOREIGN KEY (room_type_id) REFERENCES room_type (room_type_id),
    CONSTRAINT ck_room_status CHECK (status IN ('AVAILABLE', 'OCCUPIED', 'MAINTENANCE', 'OUT_OF_ORDER')),
    CONSTRAINT ck_room_housekeeping_status CHECK (housekeeping_status IN ('CLEAN', 'DIRTY', 'CLEANING', 'INSPECTED'))
);

-- 6. AMENITY: Danh muc tien nghi
CREATE TABLE amenity (
    amenity_id            NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    name                  VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_amenity PRIMARY KEY (amenity_id),
    CONSTRAINT uq_amenity_name UNIQUE (name)
);

-- 7. ROOM_TYPE_AMENITY: Tien nghi cua tung hang phong (quan he N-N)
CREATE TABLE room_type_amenity (
    room_type_id          NUMBER NOT NULL,
    amenity_id            NUMBER NOT NULL,
    CONSTRAINT pk_room_type_amenity PRIMARY KEY (room_type_id, amenity_id),
    CONSTRAINT fk_room_type_amenity_room_type_id FOREIGN KEY (room_type_id) REFERENCES room_type (room_type_id) ON DELETE CASCADE,
    CONSTRAINT fk_room_type_amenity_amenity_id FOREIGN KEY (amenity_id) REFERENCES amenity (amenity_id)
);

-- 8. GUEST: Ho so khach hang
CREATE TABLE guest (
    guest_id              NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    full_name             VARCHAR2(150) NOT NULL,
    phone                 VARCHAR2(20),
    email                 VARCHAR2(150),
    gender                VARCHAR2(10),
    date_of_birth         DATE,
    nationality           VARCHAR2(50) DEFAULT 'Viet Nam',
    id_type               VARCHAR2(10),
    id_number             VARCHAR2(30),
    address               VARCHAR2(500),
    loyalty_tier          VARCHAR2(10) DEFAULT 'NONE' NOT NULL,
    loyalty_points        NUMBER(10) DEFAULT 0 NOT NULL,
    created_at            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_guest PRIMARY KEY (guest_id),
    CONSTRAINT uq_guest_identity UNIQUE (id_type, id_number),
    CONSTRAINT ck_guest_gender CHECK (gender IN ('MALE', 'FEMALE', 'OTHER')),
    CONSTRAINT ck_guest_id_type CHECK (id_type IN ('CCCD', 'CMND', 'PASSPORT')),
    CONSTRAINT ck_guest_loyalty_tier CHECK (loyalty_tier IN ('NONE', 'SILVER', 'GOLD', 'PLATINUM'))
);

-- 9. RESERVATION: Don dat phong
CREATE TABLE reservation (
    reservation_id        NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    reservation_code      VARCHAR2(20) NOT NULL,
    guest_id              NUMBER NOT NULL,
    booking_source        VARCHAR2(15) DEFAULT 'WALK_IN' NOT NULL,
    status                VARCHAR2(15) DEFAULT 'CONFIRMED' NOT NULL,
    check_in_date         DATE NOT NULL,
    check_out_date        DATE NOT NULL,
    adults                NUMBER(2) DEFAULT 1 NOT NULL,
    children              NUMBER(2) DEFAULT 0 NOT NULL,
    total_amount          NUMBER(15,0) DEFAULT 0 NOT NULL,
    deposit_amount        NUMBER(15,0) DEFAULT 0 NOT NULL,
    note                  VARCHAR2(500),
    created_by            NUMBER,
    created_at            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_reservation PRIMARY KEY (reservation_id),
    CONSTRAINT uq_reservation_reservation_code UNIQUE (reservation_code),
    CONSTRAINT fk_reservation_guest_id FOREIGN KEY (guest_id) REFERENCES guest (guest_id),
    CONSTRAINT fk_reservation_created_by FOREIGN KEY (created_by) REFERENCES users (user_id),
    CONSTRAINT ck_reservation_booking_source CHECK (booking_source IN ('WALK_IN', 'PHONE', 'WEBSITE', 'OTA', 'OTHER')),
    CONSTRAINT ck_reservation_status CHECK (status IN ('PENDING', 'CONFIRMED', 'CHECKED_IN', 'CHECKED_OUT', 'CANCELLED', 'NO_SHOW')),
    CONSTRAINT ck_reservation_dates CHECK (check_out_date > check_in_date),
    CONSTRAINT ck_reservation_amounts CHECK (total_amount >= 0 AND deposit_amount >= 0)
);

-- 10. RESERVATION_ROOM: Tung phong trong mot don dat (room_id NULL cho den khi gan phong)
CREATE TABLE reservation_room (
    reservation_room_id   NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    reservation_id        NUMBER NOT NULL,
    room_type_id          NUMBER NOT NULL,
    room_id               NUMBER,
    price_per_night       NUMBER(15,0) NOT NULL,
    status                VARCHAR2(15) DEFAULT 'BOOKED' NOT NULL,
    CONSTRAINT pk_reservation_room PRIMARY KEY (reservation_room_id),
    CONSTRAINT fk_reservation_room_reservation_id FOREIGN KEY (reservation_id) REFERENCES reservation (reservation_id) ON DELETE CASCADE,
    CONSTRAINT fk_reservation_room_room_type_id FOREIGN KEY (room_type_id) REFERENCES room_type (room_type_id),
    CONSTRAINT fk_reservation_room_room_id FOREIGN KEY (room_id) REFERENCES room (room_id),
    CONSTRAINT ck_reservation_room_price_per_night CHECK (price_per_night >= 0),
    CONSTRAINT ck_reservation_room_status CHECK (status IN ('BOOKED', 'CHECKED_IN', 'CHECKED_OUT', 'CANCELLED'))
);

-- 11. ROOM_NIGHT: Giu cho theo dem; khoa chinh (room_id, stay_date) chong dat trung phong
CREATE TABLE room_night (
    room_id               NUMBER NOT NULL,
    stay_date             DATE NOT NULL,
    reservation_room_id   NUMBER NOT NULL,
    CONSTRAINT pk_room_night PRIMARY KEY (room_id, stay_date),
    CONSTRAINT fk_room_night_room_id FOREIGN KEY (room_id) REFERENCES room (room_id),
    CONSTRAINT fk_room_night_reservation_room_id FOREIGN KEY (reservation_room_id) REFERENCES reservation_room (reservation_room_id) ON DELETE CASCADE
);

-- 12. STAY: Luot luu tru thuc te (check-in/check-out)
CREATE TABLE stay (
    stay_id               NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    reservation_room_id   NUMBER NOT NULL,
    room_id               NUMBER NOT NULL,
    actual_check_in       TIMESTAMP NOT NULL,
    actual_check_out      TIMESTAMP,
    status                VARCHAR2(15) DEFAULT 'IN_HOUSE' NOT NULL,
    checked_in_by         NUMBER,
    checked_out_by        NUMBER,
    CONSTRAINT pk_stay PRIMARY KEY (stay_id),
    CONSTRAINT uq_stay_reservation_room_id UNIQUE (reservation_room_id),
    CONSTRAINT fk_stay_reservation_room_id FOREIGN KEY (reservation_room_id) REFERENCES reservation_room (reservation_room_id),
    CONSTRAINT fk_stay_room_id FOREIGN KEY (room_id) REFERENCES room (room_id),
    CONSTRAINT fk_stay_checked_in_by FOREIGN KEY (checked_in_by) REFERENCES users (user_id),
    CONSTRAINT fk_stay_checked_out_by FOREIGN KEY (checked_out_by) REFERENCES users (user_id),
    CONSTRAINT ck_stay_status CHECK (status IN ('IN_HOUSE', 'CHECKED_OUT')),
    CONSTRAINT ck_stay_times CHECK (actual_check_out IS NULL OR actual_check_out >= actual_check_in)
);

-- 13. HOTEL_SERVICE: Danh muc dich vu phat sinh
CREATE TABLE hotel_service (
    service_id            NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    name                  VARCHAR2(150) NOT NULL,
    category              VARCHAR2(15) DEFAULT 'OTHER' NOT NULL,
    unit                  VARCHAR2(20) NOT NULL,
    unit_price            NUMBER(15,0) NOT NULL,
    is_active             BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT pk_hotel_service PRIMARY KEY (service_id),
    CONSTRAINT uq_hotel_service_name UNIQUE (name),
    CONSTRAINT ck_hotel_service_category CHECK (category IN ('FOOD', 'LAUNDRY', 'MINIBAR', 'SPA', 'TRANSPORT', 'OTHER')),
    CONSTRAINT ck_hotel_service_unit_price CHECK (unit_price >= 0)
);

-- 14. FOLIO: Hoa don tam cua mot luot luu tru (gom tien phong va dich vu)
CREATE TABLE folio (
    folio_id              NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    stay_id               NUMBER NOT NULL,
    status                VARCHAR2(10) DEFAULT 'OPEN' NOT NULL,
    total_amount          NUMBER(15,0) DEFAULT 0 NOT NULL,
    created_at            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    closed_at             TIMESTAMP,
    CONSTRAINT pk_folio PRIMARY KEY (folio_id),
    CONSTRAINT uq_folio_stay_id UNIQUE (stay_id),
    CONSTRAINT fk_folio_stay_id FOREIGN KEY (stay_id) REFERENCES stay (stay_id),
    CONSTRAINT ck_folio_status CHECK (status IN ('OPEN', 'CLOSED'))
);

-- 15. FOLIO_ITEM: Tung khoan phi trong folio (amount am khi la giam gia)
CREATE TABLE folio_item (
    item_id               NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    folio_id              NUMBER NOT NULL,
    item_type             VARCHAR2(10) NOT NULL,
    service_id            NUMBER,
    description           VARCHAR2(300),
    quantity              NUMBER(8) DEFAULT 1 NOT NULL,
    unit_price            NUMBER(15,0) NOT NULL,
    amount                NUMBER(15,0) NOT NULL,
    posted_at             TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    posted_by             NUMBER,
    CONSTRAINT pk_folio_item PRIMARY KEY (item_id),
    CONSTRAINT fk_folio_item_folio_id FOREIGN KEY (folio_id) REFERENCES folio (folio_id),
    CONSTRAINT fk_folio_item_service_id FOREIGN KEY (service_id) REFERENCES hotel_service (service_id),
    CONSTRAINT fk_folio_item_posted_by FOREIGN KEY (posted_by) REFERENCES users (user_id),
    CONSTRAINT ck_folio_item_item_type CHECK (item_type IN ('ROOM', 'SERVICE', 'PENALTY', 'DISCOUNT', 'TAX')),
    CONSTRAINT ck_folio_item_quantity CHECK (quantity > 0)
);

-- 16. PAYMENT: Thanh toan va tien coc (gan vao folio hoac don dat phong)
CREATE TABLE payment (
    payment_id            NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    folio_id              NUMBER,
    reservation_id        NUMBER,
    method                VARCHAR2(10) NOT NULL,
    amount                NUMBER(15,0) NOT NULL,
    status                VARCHAR2(10) DEFAULT 'SUCCESS' NOT NULL,
    reference_code        VARCHAR2(100),
    paid_at               TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    received_by           NUMBER,
    CONSTRAINT pk_payment PRIMARY KEY (payment_id),
    CONSTRAINT fk_payment_folio_id FOREIGN KEY (folio_id) REFERENCES folio (folio_id),
    CONSTRAINT fk_payment_reservation_id FOREIGN KEY (reservation_id) REFERENCES reservation (reservation_id),
    CONSTRAINT fk_payment_received_by FOREIGN KEY (received_by) REFERENCES users (user_id),
    CONSTRAINT ck_payment_method CHECK (method IN ('CASH', 'CARD', 'TRANSFER', 'EWALLET')),
    CONSTRAINT ck_payment_amount CHECK (amount > 0),
    CONSTRAINT ck_payment_status CHECK (status IN ('SUCCESS', 'REFUNDED', 'FAILED')),
    CONSTRAINT ck_payment_target CHECK (folio_id IS NOT NULL OR reservation_id IS NOT NULL)
);

-- 17. INVOICE: Hoa don VAT (gia niem yet da gom VAT)
CREATE TABLE invoice (
    invoice_id            NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    folio_id              NUMBER NOT NULL,
    invoice_no            VARCHAR2(30) NOT NULL,
    buyer_name            VARCHAR2(200),
    buyer_tax_code        VARCHAR2(20),
    buyer_address         VARCHAR2(500),
    subtotal              NUMBER(15,0) NOT NULL,
    vat_rate              NUMBER(4,2) DEFAULT 8 NOT NULL,
    vat_amount            NUMBER(15,0) NOT NULL,
    total_amount          NUMBER(15,0) NOT NULL,
    issued_at             TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    issued_by             NUMBER,
    CONSTRAINT pk_invoice PRIMARY KEY (invoice_id),
    CONSTRAINT uq_invoice_folio_id UNIQUE (folio_id),
    CONSTRAINT uq_invoice_invoice_no UNIQUE (invoice_no),
    CONSTRAINT fk_invoice_folio_id FOREIGN KEY (folio_id) REFERENCES folio (folio_id),
    CONSTRAINT fk_invoice_issued_by FOREIGN KEY (issued_by) REFERENCES users (user_id),
    CONSTRAINT ck_invoice_vat_rate CHECK (vat_rate BETWEEN 0 AND 100)
);

-- 18. HOUSEKEEPING_TASK: Cong viec buong phong
CREATE TABLE housekeeping_task (
    task_id               NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
    room_id               NUMBER NOT NULL,
    assigned_to           NUMBER,
    task_type             VARCHAR2(15) DEFAULT 'CLEANING' NOT NULL,
    status                VARCHAR2(15) DEFAULT 'PENDING' NOT NULL,
    note                  VARCHAR2(500),
    created_at            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    started_at            TIMESTAMP,
    finished_at           TIMESTAMP,
    CONSTRAINT pk_housekeeping_task PRIMARY KEY (task_id),
    CONSTRAINT fk_housekeeping_task_room_id FOREIGN KEY (room_id) REFERENCES room (room_id),
    CONSTRAINT fk_housekeeping_task_assigned_to FOREIGN KEY (assigned_to) REFERENCES employee (employee_id),
    CONSTRAINT ck_housekeeping_task_task_type CHECK (task_type IN ('CLEANING', 'TURNDOWN', 'INSPECTION', 'DEEP_CLEAN')),
    CONSTRAINT ck_housekeeping_task_status CHECK (status IN ('PENDING', 'IN_PROGRESS', 'DONE'))
);

